"""Profile the eCommerce customer-support dataset and write docs/DATA_PROFILE.md.

Usage:  python ml/profile_dataset.py [--csv data/ecommerce_support.csv] [--out docs/DATA_PROFILE.md]
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]

TIMESTAMP_COLUMNS = {
    "order_date_time": "%d/%m/%Y %H:%M",
    "Issue_reported at": "%d/%m/%Y %H:%M",
    "issue_responded": "%d/%m/%Y %H:%M",
    "Survey_response_Date": "%d-%b-%y",
}


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def distribution(series: pd.Series, top: int | None = None) -> pd.DataFrame:
    counts = series.value_counts(dropna=False)
    if top:
        counts = counts.head(top)
    total = len(series)
    return pd.DataFrame(
        {
            "value": counts.index.astype(str),
            "rows": counts.values,
            "share": [f"{c / total:.1%}" for c in counts.values],
        }
    )


def profile(csv_path: Path) -> str:
    df = pd.read_csv(csv_path)
    n = len(df)
    out: list[str] = []
    out.append("# Data profile — eCommerce Customer Service Satisfaction\n")
    out.append(
        f"Generated by `ml/profile_dataset.py` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC "
        f"from `{csv_path.relative_to(ROOT).as_posix()}`.\n"
    )
    out.append(
        f"**Rows:** {n:,} · **Columns:** {df.shape[1]} · **Duplicate `Unique id`s:** "
        f"{df['Unique id'].duplicated().sum()}\n"
    )

    # ---------- columns ----------
    out.append("## Columns\n")
    col_rows = []
    for c in df.columns:
        s = df[c]
        non_null = s.notna() & (s.astype(str).str.strip() != "")
        example = s[non_null].iloc[0] if non_null.any() else ""
        example = str(example)[:40].replace("|", "/")
        col_rows.append(
            {
                "column": f"`{c}`",
                "dtype": str(s.dtype),
                "filled": f"{non_null.mean():.1%}",
                "nulls": int((~non_null).sum()),
                "unique": int(s.nunique()),
                "example": example,
            }
        )
    out.append(md_table(pd.DataFrame(col_rows)) + "\n")

    # ---------- labels ----------
    out.append("## Category (`category`) — 12 classes, used as the category label\n")
    out.append(md_table(distribution(df["category"])) + "\n")
    out.append(f"## Sub-category (`Sub-category`) — {df['Sub-category'].nunique()} classes, used as the intent label\n")
    out.append("Top 25 shown; the tail is very long (many classes have < 50 rows).\n")
    out.append(md_table(distribution(df["Sub-category"], top=25)) + "\n")
    multi = df.groupby("Sub-category")["category"].nunique()
    shared = multi[multi > 1]
    out.append(
        f"Sub-categories appearing under more than one category: "
        f"{', '.join(f'`{s}` ({c})' for s, c in shared.items()) or 'none'}.\n"
    )

    # ---------- channel ----------
    out.append("## Channel (`channel_name`)\n")
    out.append(md_table(distribution(df["channel_name"])) + "\n")

    # ---------- remarks ----------
    remarks = df["Customer Remarks"].fillna("").astype(str).str.strip()
    has = remarks != ""
    words = remarks[has].str.split().str.len()
    out.append("## Remark coverage (`Customer Remarks`)\n")
    out.append(
        f"- Rows with a remark: **{has.sum():,} ({has.mean():.1%})**; empty: {(~has).sum():,}.\n"
        f"- Words per remark: median {words.median():.0f}, mean {words.mean():.1f}, "
        f"p90 {words.quantile(0.9):.0f}, max {words.max()}.\n"
        f"- Remarks with ≥ 5 words: {(words >= 5).sum():,} ({(words >= 5).sum() / n:.1%} of all rows).\n"
        f"- Distinct remark strings: {remarks[has].str.lower().nunique():,}.\n"
    )
    out.append("Most frequent remarks (they are mostly post-contact survey feedback, not complaint text):\n")
    top_remarks = remarks[has].str.lower().value_counts().head(15)
    out.append(md_table(pd.DataFrame({"remark": top_remarks.index, "rows": top_remarks.values})) + "\n")
    cov = df.assign(has=has).groupby("category")["has"].mean().sort_values(ascending=False)
    out.append("Remark coverage by category:\n")
    out.append(md_table(pd.DataFrame({"category": cov.index, "with remark": [f"{v:.1%}" for v in cov.values]})) + "\n")
    out.append(
        "**Implication:** empty remarks get a templated description at import time "
        "(`text_is_template = true`) and are excluded from model training.\n"
    )

    # ---------- CSAT ----------
    out.append("## CSAT (`CSAT Score`)\n")
    csat = df["CSAT Score"].value_counts().sort_index()
    out.append(
        md_table(
            pd.DataFrame({"score": csat.index, "rows": csat.values, "share": [f"{v / n:.1%}" for v in csat.values]})
        )
        + "\n"
    )
    out.append(f"Mean CSAT {df['CSAT Score'].mean():.2f}. Mean CSAT by category:\n")
    by_cat = df.groupby("category")["CSAT Score"].agg(["mean", "count"]).sort_values("mean")
    out.append(
        md_table(
            pd.DataFrame(
                {"category": by_cat.index, "mean CSAT": by_cat["mean"].round(2).values, "rows": by_cat["count"].values}
            )
        )
        + "\n"
    )

    # ---------- timestamps ----------
    out.append("## Timestamps\n")
    ts_rows = []
    parsed = {}
    for col, fmt in TIMESTAMP_COLUMNS.items():
        p = pd.to_datetime(df[col], format=fmt, errors="coerce")
        parsed[col] = p
        ts_rows.append(
            {
                "column": f"`{col}`",
                "format": f"`{fmt}`",
                "parsed": f"{p.notna().mean():.1%}",
                "min": p.min(),
                "max": p.max(),
            }
        )
    out.append(md_table(pd.DataFrame(ts_rows)) + "\n")
    frt = (parsed["issue_responded"] - parsed["Issue_reported at"]).dt.total_seconds() / 60
    valid = frt[frt.notna()]
    out.append(
        f"First-response minutes (`issue_responded − Issue_reported at`): median {valid.median():.0f}, "
        f"mean {valid.mean():.0f}, p90 {valid.quantile(0.9):.0f}; negative values: {(valid < 0).sum()} "
        f"(treated as invalid at import).\n"
    )
    daily = parsed["Issue_reported at"].dt.date.value_counts().sort_index()
    out.append(
        f"Reported-at spans {daily.index.min()} → {daily.index.max()} ({len(daily)} days, "
        f"{daily.mean():.0f} tickets/day on average, min {daily.min()}, max {daily.max()}).\n"
    )

    # ---------- partial fields ----------
    out.append("## Partial fields (city, product, price)\n")
    for c in ["Customer_City", "Product_category", "Item_price", "Order_id", "connected_handling_time"]:
        out.append(f"- `{c}`: {df[c].notna().mean():.1%} filled, {df[c].nunique():,} distinct values.\n")
    out.append("\nProduct categories:\n")
    out.append(md_table(distribution(df["Product_category"].dropna())) + "\n")
    price = df["Item_price"].dropna()
    out.append(
        f"Item price (₹): median {price.median():,.0f}, mean {price.mean():,.0f}, p90 {price.quantile(0.9):,.0f}, "
        f"max {price.max():,.0f}; ≥ ₹10,000: {(price >= 10000).sum():,} rows.\n"
    )
    cities = df["Customer_City"].value_counts().head(10)
    out.append("\nTop cities:\n")
    out.append(md_table(pd.DataFrame({"city": cities.index, "rows": cities.values})) + "\n")
    out.append("**Implication:** city / product / price charts must display their data coverage %.\n")

    # ---------- people ----------
    out.append("## People (`Agent_name`, `Supervisor`, `Manager`, `Tenure Bucket`, `Agent Shift`)\n")
    out.append(
        f"- {df['Agent_name'].nunique():,} agents, {df['Supervisor'].nunique()} supervisors, "
        f"{df['Manager'].nunique()} managers. Each agent reports to exactly "
        f"{df.groupby('Agent_name')['Supervisor'].nunique().max()} supervisor.\n"
    )
    per_agent = df["Agent_name"].value_counts()
    out.append(f"- Tickets per agent: median {per_agent.median():.0f}, max {per_agent.max()}.\n")
    out.append("\nTenure bucket:\n")
    out.append(md_table(distribution(df["Tenure Bucket"])) + "\n")
    out.append("Agent shift:\n")
    out.append(md_table(distribution(df["Agent Shift"])) + "\n")

    out.append("## Known limitations\n")
    out.append(
        "- Remarks are short (median 3 words) and are mostly satisfaction feedback, so text alone carries a weak "
        "category signal; ML results must be read with that in mind.\n"
        "- No priority labels exist → priority is rule-based (see `docs/PRIORITY_RULES.md`).\n"
        "- No customer identifiers; every `Order_id` is unique, so repeat contact is detected from text cues "
        '("already contacted", "three times").\n'
        "- City / product / price are ~20% filled → charts show coverage.\n"
        "- Only one month of data (August 2023).\n"
    )
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--csv", default=str(ROOT / "data" / "ecommerce_support.csv"))
    parser.add_argument("--out", default=str(ROOT / "docs" / "DATA_PROFILE.md"))
    args = parser.parse_args()
    text = profile(Path(args.csv))
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
